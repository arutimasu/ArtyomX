; bootloader.asm
[BITS 16]        ; Указываем, что это 16-битный код
[ORG 0x7C00]    ; Адрес загрузки загрузчика

start:
    ; Инициализация сегментов
    xor ax, ax
    mov ds, ax
    mov es, ax

    ; Установка чтения сектора
    mov si, data_buffer
    mov ax, 0x0201 ; BIOS-прерывание для чтения сектора
    mov bx, 0x0000 ; Загрузить данные в начало памяти
    mov cx, 1      ; Чтение первого сектора
    mov dx, 0x00   ; Дисковод 0 (флоппи)
    int 0x13       ; Вызов BIOS-прерывания

    ; Проверка на успешность
    jc disk_error

    ; Переход к загруженной программе
    jmp 0x0000:0x7E00 ; Переход на адрес загрузки программы

disk_error:
    ; Тут можно вывести сообщение об ошибке
    jmp disk_error ; Зациклиться в случае ошибки

data_buffer:
    times 512 db 0 ; Буфер для чтения сектора (512 байт)

times 544 - ($ - $$) db 0 ; Заполнение до 510 байт
dw 0xAA55 ; Загрузочный супер-байт